CHARSET = tuple(sorted(_RAW.keys()))


def glyph_rows(ch):
    if ch not in _RAW:
        raise KeyError(f"glyph not available in built-in font: {ch!r}")
    return _RAW[ch]


def glyph_bitmap(ch):
    """Return a ``(GLYPH_H, GLYPH_W)`` uint8 bitmap (1 = stroke)."""
    rows = glyph_rows(ch)
    bmp = [[(row >> (GLYPH_W - 1 - col)) & 1 for col in range(GLYPH_W)]
           for row in rows]
    return bmp


def render_glyph(ch, scale=2, fg=0, bg=255):
    """Render one glyph to a scaled uint8 grayscale tile."""
    bmp = glyph_bitmap(ch)
    tile = [[bg] * (GLYPH_W * scale) for _ in range(GLYPH_H * scale)]
    for ry, row in enumerate(bmp):
        for rx, val in enumerate(row):
            if val:
                for dy in range(scale):
                    for dx in range(scale):
                        tile[ry * scale + dy][rx * scale + dx] = fg
    return tile


def scaled_metrics(scale):
    return GLYPH_W * scale, GLYPH_H * scale

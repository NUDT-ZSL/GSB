"""Deterministic PNG codec implemented with the Python standard library only.

Supports 8-bit grayscale / RGB / RGBA images and filter types 0-4 on decode.
Encoding always emits filter type 0 (None) scanlines with a single IDAT chunk,
which keeps generated bytes fully deterministic.
"""
from __future__ import annotations

import struct
import zlib

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"

COLOR_GRAY = 0
COLOR_RGB = 2
COLOR_RGBA = 6
_CHANNELS = {COLOR_GRAY: 1, COLOR_RGB: 3, COLOR_RGBA: 4}


class PngError(ValueError):
    """Raised when a PNG container or stream cannot be parsed."""


def _paeth(a: int, b: int, c: int) -> int:
    p = a + b - c
    pa = abs(p - a)
    pb = abs(p - b)
    pc = abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c


def _iter_chunks(data: bytes):
    offset = 0
    while offset < len(data):
        if offset + 8 > len(data):
            raise PngError("truncated chunk header")
        length = struct.unpack(">I", data[offset:offset + 4])[0]
        ctype = data[offset + 4:offset + 8]
        start = offset + 8
        end = start + length
        if end > len(data) - 4:
            raise PngError("truncated chunk body")
        body = data[start:end]
        stored_crc = struct.unpack(">I", data[end:end + 4])[0]
        if zlib.crc32(ctype + body) & 0xFFFFFFFF != stored_crc:
            raise PngError("chunk CRC mismatch")
        yield ctype, body
        offset = end + 4


def decode_png(data: bytes):
    """Decode PNG bytes into a uint8 numpy array of shape (H, W[, C])."""
    import numpy as np

    if not isinstance(data, (bytes, bytearray)):
        raise PngError("PNG input must be bytes")
    if len(data) < 8 or bytes(data[:8]) != PNG_SIGNATURE:
        raise PngError("invalid PNG container header")

    width = height = bit_depth = color_type = None
    interlace = 0
    idat = bytearray()
    for ctype, body in _iter_chunks(bytes(data[8:])):
        if ctype == b"IHDR":
            if len(body) != 13:
                raise PngError("invalid IHDR length")
            (width, height, bit_depth, color_type, _comp, _filt,
             interlace) = struct.unpack(">IIBBBBB", body)
        elif ctype == b"IDAT":
            idat.extend(body)
        elif ctype == b"IEND":
            break
    if width is None:
        raise PngError("missing IHDR chunk")
    if interlace != 0:
        raise PngError("interlaced PNG is not supported")
    if bit_depth != 8:
        raise PngError(f"unsupported bit depth {bit_depth}")
    if color_type not in _CHANNELS:
        raise PngError(f"unsupported color type {color_type}")
    channels = _CHANNELS[color_type]
    if not idat:
        raise PngError("missing IDAT chunk")

    raw = zlib.decompress(bytes(idat))
    stride = width * channels
    expected = height * (stride + 1)
    if len(raw) != expected:
        raise PngError("decompressed stream has unexpected length")

    out = np.zeros((height, stride), dtype=np.uint8)
    prev = np.zeros(stride, dtype=np.uint8)
    pos = 0
    for row in range(height):
        filter_type = raw[pos]
        line = np.frombuffer(raw[pos + 1:pos + 1 + stride], dtype=np.uint8).copy()
        pos += stride + 1
        if filter_type == 0:
            recon = line
        elif filter_type == 1:
            recon = line.copy()
            for i in range(channels, stride):
                recon[i] = (line[i] + recon[i - channels]) & 0xFF
        elif filter_type == 2:
            recon = (line.astype(np.uint16) + prev.astype(np.uint16)) & 0xFF
            recon = recon.astype(np.uint8)
        elif filter_type == 3:
            recon = line.copy()
            for i in range(stride):
                left = recon[i - channels] if i >= channels else 0
                recon[i] = (line[i] + ((left + int(prev[i])) >> 1)) & 0xFF
        elif filter_type == 4:
            recon = line.copy()
            for i in range(stride):
                left = int(recon[i - channels]) if i >= channels else 0
                up = int(prev[i])
                up_left = int(prev[i - channels]) if i >= channels else 0
                recon[i] = (line[i] + _paeth(left, up, up_left)) & 0xFF
        else:
            raise PngError(f"unsupported filter type {filter_type}")
        out[row] = recon
        prev = recon

    if channels == 1:
        return out.reshape(height, width).astype(np.uint8)
    return out.reshape(height, width, channels).astype(np.uint8)


def encode_png(image) -> bytes:
    """Encode an HxW or HxWxC uint8 array into deterministic PNG bytes."""
    import numpy as np

    arr = np.asarray(image)
    if arr.dtype != np.uint8:
        raise PngError("only uint8 images can be encoded")
    if arr.ndim == 2:
        color_type = COLOR_GRAY
        height, width = arr.shape
        channels = 1
    elif arr.ndim == 3 and arr.shape[2] in (1, 3, 4):
        height, width, channels = arr.shape
        color_type = {1: COLOR_GRAY, 3: COLOR_RGB, 4: COLOR_RGBA}[channels]
        if channels == 1:
            arr = arr[:, :, 0]
    else:
        raise PngError("unsupported image shape")

    def chunk(ctype: bytes, body: bytes) -> bytes:
        return (struct.pack(">I", len(body)) + ctype + body +
                struct.pack(">I", zlib.crc32(ctype + body) & 0xFFFFFFFF))

    ihdr = struct.pack(">IIBBBBB", width, height, 8, color_type, 0, 0, 0)
    flat = arr.reshape(height, width * channels)
    scanlines = bytearray()
    for row in range(height):
        scanlines.append(0)
        scanlines.extend(flat[row].tobytes())
    idat = zlib.compress(bytes(scanlines), level=9)
    return PNG_SIGNATURE + chunk(b"IHDR", ihdr) + chunk(b"IDAT", idat) + chunk(b"IEND", b"")

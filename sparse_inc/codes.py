"""Stable business codes and process exit-code mapping."""

from __future__ import annotations

OK = "OK"

E_SHAPE_INVALID = "E_SHAPE_INVALID"
E_DTYPE_UNSUPPORTED = "E_DTYPE_UNSUPPORTED"
E_CSR_STRUCT = "E_CSR_STRUCT"
E_NNZ_MISMATCH = "E_NNZ_MISMATCH"

E_WRITE_STALE = "E_WRITE_STALE"
E_WRITE_CORRUPT = "E_WRITE_CORRUPT"
E_WRITE_RANGE = "E_WRITE_RANGE"
E_WRITE_CONFLICT = "E_WRITE_CONFLICT"
E_WRITE_BUSY = "E_WRITE_BUSY"
E_RESOURCE_LIMIT = "E_RESOURCE_LIMIT"

E_INCONSISTENT = "E_INCONSISTENT"

E_SNAPSHOT_ROLLBACK = "E_SNAPSHOT_ROLLBACK"
E_SNAPSHOT_CORRUPT = "E_SNAPSHOT_CORRUPT"

E_RECOVERY_FAILED = "E_RECOVERY_FAILED"
E_INVALID_REQUEST = "E_INVALID_REQUEST"
E_CASE_NOT_FOUND = "E_CASE_NOT_FOUND"


EXIT_CODES = {
    OK: 0,
    E_SHAPE_INVALID: 10,
    E_DTYPE_UNSUPPORTED: 11,
    E_CSR_STRUCT: 12,
    E_NNZ_MISMATCH: 13,
    E_WRITE_STALE: 20,
    E_WRITE_CORRUPT: 21,
    E_WRITE_RANGE: 22,
    E_WRITE_CONFLICT: 23,
    E_WRITE_BUSY: 24,
    E_RESOURCE_LIMIT: 25,
    E_INCONSISTENT: 30,
    E_SNAPSHOT_ROLLBACK: 40,
    E_SNAPSHOT_CORRUPT: 41,
    E_RECOVERY_FAILED: 42,
    E_INVALID_REQUEST: 43,
    E_CASE_NOT_FOUND: 44,
}


def exit_code_for(code: str) -> int:
    """Return the stable CLI exit code for a business code."""

    return EXIT_CODES.get(code, 1)

#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""make_samples.py — 确定性生成全部测试样本(无随机数)

生成到 samples/:
  texture.png             漫反射纹理(红绿渐变 + 白色网格线, 无蓝色分量便于检测棋盘格)
  cube.obj                默认立方体(12 三角面, UV 均在 [0,1])
  sphere.obj              无法线球体(仅 v/f 行, 无 vn/vt)
  plane_uv15.obj          平面, 右半 UV 取到 1.5 (越界), 左半正常
  cube_degenerate.obj     立方体 + 第 12 号(0 基)退化共线三角形
  views.json              四视角配置(front/side/top/iso)
  views_invalid_side.json side 视角 azimuth 为非法字符串
  broken.obj              损坏的网格文件
"""
import json
import os

import numpy as np
from PIL import Image

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "samples")


def write_obj(path, vertices, faces, uvs=None):
    """faces 为 0 基索引; uvs 为每顶点 UV(与 vertices 等长)。"""
    lines = ["# generated by make_samples.py (deterministic)"]
    for v in vertices:
        lines.append(f"v {v[0]:.9g} {v[1]:.9g} {v[2]:.9g}")
    if uvs is not None:
        for t in uvs:
            lines.append(f"vt {t[0]:.9g} {t[1]:.9g}")
        for f in faces:
            lines.append("f " + " ".join(f"{i + 1}/{i + 1}" for i in f))
    else:
        for f in faces:
            lines.append("f " + " ".join(str(i + 1) for i in f))
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


def make_texture():
    x = np.linspace(0.0, 1.0, 256)
    X, Y = np.meshgrid(x, x)
    r = X
    g = Y
    b = np.full_like(X, 0.15)
    img = np.stack([r, g, b], axis=-1)
    # 白色网格线, 每 32 像素
    grid = (np.arange(256) % 32) == 0
    img[grid, :, :] = 1.0
    img[:, grid, :] = 1.0
    Image.fromarray((img * 255).astype(np.uint8), "RGB").save(
        os.path.join(OUT, "texture.png"))


def make_cube():
    # 边长 1, 每面 4 顶点(带独立 UV), 共 24 顶点 12 三角面
    s = 0.5
    quads = [  # (4 顶点, 法向朝外)
        [(-s, -s, s), (s, -s, s), (s, s, s), (-s, s, s)],          # 前 +z
        [(s, -s, -s), (-s, -s, -s), (-s, s, -s), (s, s, -s)],      # 后 -z
        [(s, -s, s), (s, -s, -s), (s, s, -s), (s, s, s)],          # 右 +x
        [(-s, -s, -s), (-s, -s, s), (-s, s, s), (-s, s, -s)],      # 左 -x
        [(-s, s, s), (s, s, s), (s, s, -s), (-s, s, -s)],          # 顶 +y
        [(-s, -s, -s), (s, -s, -s), (s, -s, s), (-s, -s, s)],      # 底 -y
    ]
    face_uv = [(0.0, 0.0), (1.0, 0.0), (1.0, 1.0), (0.0, 1.0)]
    vertices, uvs, faces = [], [], []
    for q in quads:
        base = len(vertices)
        vertices.extend(q)
        uvs.extend(face_uv)
        faces.append([base, base + 1, base + 2])
        faces.append([base, base + 2, base + 3])
    return vertices, uvs, faces


def make_sphere():
    """icosphere(subdiv=3), 只写 v/f 行 —— 无法线、无纹理坐标。"""
    import trimesh
    mesh = trimesh.creation.icosphere(subdivisions=3, radius=1.0)
    write_obj(os.path.join(OUT, "sphere.obj"),
              mesh.vertices.tolist(), mesh.faces.tolist())


def make_plane():
    # 左右两个方格拼成的平面(z=0), 左格 UV∈[0,1], 右格 u∈[1,1.5] 越界
    vertices = [(-1.0, -0.5, 0.0), (0.0, -0.5, 0.0), (1.0, -0.5, 0.0),
                (-1.0, 0.5, 0.0), (0.0, 0.5, 0.0), (1.0, 0.5, 0.0)]
    uvs = [(0.0, 0.0), (1.0, 0.0), (1.5, 0.0),
           (0.0, 1.0), (1.0, 1.0), (1.5, 1.0)]
    faces = [[0, 1, 4], [0, 4, 3],   # 左格: UV 正常
             [1, 2, 5], [1, 5, 4]]   # 右格: u 越界(1.5)
    write_obj(os.path.join(OUT, "plane_uv15.obj"), vertices, faces, uvs)


def make_degenerate_cube():
    vertices, uvs, faces = make_cube()
    # 追加一个共线退化三角形(位于立方体顶前棱上), 0 基索引 12
    base = len(vertices)
    vertices.extend([(-0.5, 0.5, 0.5), (0.0, 0.5, 0.5), (0.5, 0.5, 0.5)])
    uvs.extend([(0.0, 0.0), (0.5, 0.0), (1.0, 0.0)])
    faces.append([base, base + 1, base + 2])
    write_obj(os.path.join(OUT, "cube_degenerate.obj"), vertices, faces, uvs)


def make_views():
    views = {"views": [
        {"name": "front", "azimuth": 0, "elevation": 10},
        {"name": "side", "azimuth": 90, "elevation": 10},
        {"name": "top", "azimuth": 0, "elevation": 90},
        {"name": "iso", "azimuth": 45, "elevation": 35},
    ]}
    with open(os.path.join(OUT, "views.json"), "w", encoding="utf-8") as fh:
        json.dump(views, fh, ensure_ascii=False, indent=2)
    bad = {"views": [
        {"name": "front", "azimuth": 0, "elevation": 10},
        {"name": "side", "azimuth": "east", "elevation": 10},   # 非法: 字符串
        {"name": "top", "azimuth": 0, "elevation": 90},
        {"name": "iso", "azimuth": 45, "elevation": 35},
    ]}
    with open(os.path.join(OUT, "views_invalid_side.json"), "w", encoding="utf-8") as fh:
        json.dump(bad, fh, ensure_ascii=False, indent=2)


def make_broken():
    with open(os.path.join(OUT, "broken.obj"), "w", encoding="utf-8") as fh:
        fh.write("this is not a valid OBJ file\n")
        fh.write("### garbage ###\n")
        fh.write("v a b c\nf x y z\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    make_texture()
    v, t, f = make_cube()
    write_obj(os.path.join(OUT, "cube.obj"), v, f, t)
    make_sphere()
    make_plane()
    make_degenerate_cube()
    make_views()
    make_broken()
    print("样本已生成到", OUT)


if __name__ == "__main__":
    main()

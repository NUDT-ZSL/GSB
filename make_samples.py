#!/usr/bin/env python3
"""确定性生成上传核验样本（仅标准库）。

生成内容（默认输出目录 ``demo_out``）::

    demo_out/
      .upload-audit-sample          # 目录归属标记，--force 时用于安全清理
      outside/                      # 上传目录之外的目标，用于穿越/逃逸样本
        secret.txt
        abs_target.txt
      before/                       # 修复前：存在穿越与伪装
        upload/
          notes.txt  photo.png  payload.exe  dup.txt
          run_sample.py  run_sample.cmd      # 可执行标记样本（绝不应被运行）
          escape_dir -> outside              # 目录联接/符号链接逃逸
        manifest.csv
      after/                        # 修复后：穿越与伪装均已消除
        upload/ ...
        manifest.csv
      regression/                   # 修复后 + 一个新引入的伪装风险
        upload/ ...
        manifest.csv

所有文件内容与清单行均为固定文本，重复生成结果一致（不含时间戳）。
生成器只会在带有 ``.upload-audit-sample`` 标记的目录内清理，避免误删。
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys

MARKER_NAME = ".upload-audit-sample"
MARKER_CONTENT = "generated by make_samples.py\n"
EXEC_MARKER_NAME = "EXECUTED_MARKER.txt"


# --------------------------------------------------------------------------- #
# 基础工具
# --------------------------------------------------------------------------- #
def write_text(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def write_bytes(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as handle:
        handle.write(data)


def make_dir_link(target, link_path):
    """创建目录链接（Windows 用目录联接，无需管理员权限；其他平台用 symlink）。"""
    if os.path.lexists(link_path):
        return
    if sys.platform == "win32":
        try:
            import _winapi

            _winapi.CreateJunction(target, link_path)
            return
        except (ImportError, OSError, AttributeError):
            pass
    os.symlink(target, link_path, target_is_directory=True)


def executable_sample_py(marker_path):
    """若被 Python 执行，会写出标记文件。扫描器绝不能执行它。"""
    return (
        "#!/usr/bin/env python3\n"
        '"""可执行标记样本：一旦被执行就会写出 '
        + EXEC_MARKER_NAME
        + '。"""\n'
        "from pathlib import Path\n"
        "\n"
        f"Path({marker_path!r}).write_text('EXECUTED\\n', encoding='utf-8')\n"
    )


def executable_sample_cmd(marker_path):
    return (
        "@echo off\r\n"
        "rem 可执行标记样本：一旦被执行就会写出 " + EXEC_MARKER_NAME + "\r\n"
        'echo EXECUTED> "' + marker_path + '"\r\n'
    )


def write_manifest(path, rows, *, include_blank=True, malformed=False):
    """写清单 CSV（UTF-8，无 BOM）。rows 按给定顺序写入，故意打乱。"""
    lines = ["relative_path,declared_ext"]
    for index, (rel_path, ext) in enumerate(rows):
        lines.append(f"{rel_path},{ext}")
        if include_blank and index == 1:
            lines.append("")  # 空行：应被跳过
    if malformed:
        lines.append("only_one_column_no_comma")  # 列数异常：应记无法判定
    write_text(path, "\n".join(lines) + "\n")


# --------------------------------------------------------------------------- #
# 场景
# --------------------------------------------------------------------------- #
def build(root):
    outside = os.path.join(root, "outside")
    write_text(
        os.path.join(outside, "secret.txt"),
        "OUTSIDE-SECRET: 该文件位于上传目录之外，不应被上传服务读写。\n",
    )
    write_text(
        os.path.join(outside, "abs_target.txt"),
        "OUTSIDE-ABS: 通过绝对路径引用的外部文件。\n",
    )

    marker_path = os.path.join(root, EXEC_MARKER_NAME)
    if os.path.exists(marker_path):
        os.remove(marker_path)

    # ---------------- 修复前 ----------------
    before_upload = os.path.join(root, "before", "upload")
    write_text(os.path.join(before_upload, "notes.txt"), "hello upload\n")
    write_bytes(
        os.path.join(before_upload, "photo.png"),
        b"\x89PNG\r\n\x1a\n" + b"\x00" * 16,
    )
    write_bytes(
        os.path.join(before_upload, "payload.exe"),
        b"MZ\x90\x00" + b"FAKE-PE-PAYLOAD" * 2,  # 伪装成图片的可执行文件内容
    )
    write_text(os.path.join(before_upload, "dup.txt"), "duplicate path sample\n")
    write_text(
        os.path.join(before_upload, "run_sample.py"),
        executable_sample_py(marker_path),
    )
    write_text(
        os.path.join(before_upload, "run_sample.cmd"),
        executable_sample_cmd(marker_path),
    )
    make_dir_link(outside, os.path.join(before_upload, "escape_dir"))

    abs_target = os.path.abspath(os.path.join(outside, "abs_target.txt"))
    before_rows = [
        # 故意乱序，用于验证输出按 relative_path 升序稳定排序
        ("notes.txt", ".txt"),
        ("photo.png", ".PNG"),              # 大小写不同 -> 安全
        ("payload.exe", ".png"),            # 声明 .png 实际 .exe -> 伪装
        ("../evil.txt", ".txt"),            # 词法跳出 -> 穿越
        ("sub/../../evil2.txt", ".txt"),    # 词法跳出（先进入再跳出）-> 穿越
        (abs_target, ".txt"),               # 绝对路径 -> 穿越
        ("escape_dir/secret.txt", ".txt"),  # 链接逃逸 -> 穿越
        ("missing.dat", ".dat"),            # 磁盘缺失 -> 无法判定
        ("run_sample.py", ".py"),           # 可执行样本，仅扫描不执行
        ("run_sample.cmd", ".cmd"),
        ("dup.txt", ".txt"),                # 重复路径第 1 次
        ("dup.txt", ".md"),                 # 重复路径第 2 次（保持原顺序）
    ]
    write_manifest(
        os.path.join(root, "before", "manifest.csv"),
        before_rows,
        include_blank=True,
        malformed=True,
    )

    # ---------------- 修复后 ----------------
    after_upload = os.path.join(root, "after", "upload")
    write_text(os.path.join(after_upload, "notes.txt"), "hello upload\n")
    write_bytes(
        os.path.join(after_upload, "photo.png"),
        b"\x89PNG\r\n\x1a\n" + b"\x00" * 16,
    )
    write_bytes(
        os.path.join(after_upload, "payload.exe"),
        b"MZ\x90\x00" + b"FAKE-PE-PAYLOAD" * 2,
    )
    write_text(os.path.join(after_upload, "dup.txt"), "duplicate path sample\n")
    write_text(os.path.join(after_upload, "missing.dat"), "now restored\n")
    write_text(
        os.path.join(after_upload, "run_sample.py"),
        executable_sample_py(marker_path),
    )
    write_text(
        os.path.join(after_upload, "run_sample.cmd"),
        executable_sample_cmd(marker_path),
    )
    # 修复后的服务：拒绝 ../ 与绝对路径，且链接在其写盘前已解析为目录内路径
    write_text(os.path.join(after_upload, "sanitized", "evil.txt"), "rejected path, stored safely\n")
    after_rows = [
        ("notes.txt", ".txt"),
        ("photo.png", ".PNG"),
        ("payload.exe", ".exe"),            # 声明与实际一致 -> 安全
        ("missing.dat", ".dat"),            # 修复后已恢复 -> 安全
        ("run_sample.py", ".py"),
        ("run_sample.cmd", ".cmd"),
        ("dup.txt", ".txt"),
        ("dup.txt", ".txt"),
        ("sanitized/evil.txt", ".txt"),     # 旧穿越请求被安全落地
    ]
    write_manifest(
        os.path.join(root, "after", "manifest.csv"),
        after_rows,
        include_blank=True,
        malformed=False,
    )

    # ---------------- 回归：修复后 + 一个新伪装 ----------------
    regression_upload = os.path.join(root, "regression", "upload")
    shutil.copytree(after_upload, regression_upload)
    write_bytes(
        os.path.join(regression_upload, "invoice.cmd"),
        b"@echo off\r\necho INVOICE\r\n",
    )
    regression_rows = list(after_rows) + [("invoice.cmd", ".pdf")]
    write_manifest(
        os.path.join(root, "regression", "manifest.csv"),
        regression_rows,
        include_blank=True,
        malformed=False,
    )

    assert_marker_absent(marker_path)


def assert_marker_absent(marker_path):
    if os.path.exists(marker_path):
        raise SystemExit(f"错误：生成阶段不应存在执行标记文件: {marker_path}")


# --------------------------------------------------------------------------- #
# 输出目录管理
# --------------------------------------------------------------------------- #
def _remove_entry(path):
    """删除单个条目；目录链接/联接只删链接本身，绝不递归进入目标。"""
    if os.path.islink(path) or is_reparse_dir(path):
        try:
            os.unlink(path)
        except OSError:
            os.rmdir(path)  # Windows 目录联接需要 rmdir
        return
    if os.path.isdir(path):
        shutil.rmtree(path)
        return
    os.remove(path)


def prepare_root(root, force):
    root = os.path.abspath(root)
    if os.path.exists(root):
        if not os.path.isdir(root):
            raise SystemExit(f"错误：输出路径不是目录: {root}")
        entries = os.listdir(root)
        marker = os.path.join(root, MARKER_NAME)
        if entries and not os.path.exists(marker):
            raise SystemExit(
                f"错误：输出目录非空且不是本工具生成（缺少 {MARKER_NAME}）: {root}\n"
                "请换一个空目录，或手工确认后清空。"
            )
        if entries and not force:
            raise SystemExit(
                f"错误：输出目录已存在: {root}\n使用 --force 重新生成样本。"
            )
        if force:
            for name in entries:
                if name == MARKER_NAME:
                    continue
                _remove_entry(os.path.join(root, name))
            if os.path.exists(marker):
                os.remove(marker)
    os.makedirs(root, exist_ok=True)
    write_text(os.path.join(root, MARKER_NAME), MARKER_CONTENT)
    return root


def is_reparse_dir(path):
    if sys.platform != "win32":
        return False
    try:
        import stat as stat_module

        attrs = os.lstat(path).st_file_attributes
        return bool(attrs & stat_module.FILE_ATTRIBUTE_REPARSE_POINT)
    except (AttributeError, OSError):
        return False


def main(argv=None):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass
    parser = argparse.ArgumentParser(
        prog="make_samples.py",
        description="确定性生成上传核验样本（修复前 / 修复后 / 回归）。",
    )
    parser.add_argument(
        "--out", default="demo_out", help="输出根目录（默认 ./demo_out）"
    )
    parser.add_argument("--force", action="store_true", help="覆盖已有样本目录")
    args = parser.parse_args(argv)

    root = prepare_root(args.out, args.force)
    build(root)

    print(f"样本已生成: {root}")
    for scenario in ("before", "after", "regression"):
        print(f"  {scenario:11s} upload   : {os.path.join(root, scenario, 'upload')}")
        print(f"  {scenario:11s} manifest : {os.path.join(root, scenario, 'manifest.csv')}")
    print(f"  执行标记（应始终不存在）: {os.path.join(root, EXEC_MARKER_NAME)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

from __future__ import annotations

import heapq
from pathlib import Path
from typing import Any, Callable

from .engine import Engine, initialize_database
from .model import Application, Catalog
from .transport import LoopbackTransport, SimulatedTransport


def _application_map(catalog: Catalog) -> dict[tuple[int, int], Application]:
    return {
        (application.seq, application.version): application
        for application in catalog.trace.applications
    }


def _lease_signature(lease: dict[str, Any]) -> dict[str, Any]:
    return {
        "lease_id": lease["lease_id"],
        "conn_id": lease["conn_id"],
        "app_seq": lease["app_seq"],
        "app_version": lease["app_version"],
        "tenant": lease["tenant"],
        "pool_label": lease["pool_label"],
        "endpoint_name": lease["endpoint_name"],
        "issued_at_ms": lease["issued_at_ms"],
        "build_latency_ms": lease["build_latency_ms"],
        "reused": lease["reused"],
    }


def replay_catalog(
    db_path: str | Path,
    catalog: Catalog,
    *,
    mode: str | None = None,
    transport_factory: Callable[[], LoopbackTransport | SimulatedTransport] | None = None,
) -> dict[str, Any]:
    """Replay a trace with injected logical clocks.

    Releases generated by queued applications are scheduled from their actual
    issue clock, not their original apply clock.
    """

    if transport_factory is None:
        transport_factory = LoopbackTransport
    init = initialize_database(
        db_path,
        catalog,
        initial_mode=mode,
    )
    applications = _application_map(catalog)
    transport = transport_factory()
    engine = Engine(db_path, transport=transport)
    issued: list[dict[str, Any]] = []
    closed: list[dict[str, Any]] = []
    seen_leases: set[str] = set()
    scheduled_releases: set[tuple[int, int]] = set()

    def record_issue(lease: dict[str, Any]) -> None:
        lease_id = str(lease["lease_id"])
        if lease_id in seen_leases:
            return
        seen_leases.add(lease_id)
        issued.append(_lease_signature(lease))

    def schedule_release(lease: dict[str, Any]) -> None:
        key = (int(lease["app_seq"]), int(lease["app_version"]))
        application = applications[key]
        if not application.release or key in scheduled_releases:
            return
        scheduled_releases.add(key)
        release_clock = int(lease["issued_at_ms"]) + application.hold_ms
        heapq.heappush(events, (release_clock, 0, application.seq, application.version))

    def process_dispatched(result: dict[str, Any]) -> None:
        for lease in result.get("dispatched", []):
            record_issue(lease)
            schedule_release(lease)
        closed.extend(result.get("closed", []))

    events: list[tuple[int, int, int, int]] = []
    for application in catalog.trace.applications:
        heapq.heappush(
            events,
            (
                application.apply_clock_ms,
                1,
                application.seq,
                application.version,
            ),
        )

    last_activity = 0
    try:
        while events:
            clock_ms, phase, app_seq, app_version = heapq.heappop(events)
            application = applications[(app_seq, app_version)]
            last_activity = max(last_activity, clock_ms)
            if phase == 0:
                result = engine.release(app_seq, app_version, clock_ms)
                process_dispatched(result)
            else:
                result = engine.acquire(application, clock_ms)
                process_dispatched(result)
                if result["status"] == "LEASED":
                    record_issue(result["lease"])
                    schedule_release(result["lease"])

        idle_timeout = catalog.config.idle_timeout_ms
        clock_step = catalog.config.clock_step_ms
        target = max(
            catalog.trace.final_clock_ms or 0,
            last_activity + idle_timeout + clock_step,
        )
        while True:
            result = engine.advance(target)
            process_dispatched(result)
            if events:
                next_clock, phase, app_seq, app_version = heapq.heappop(events)
                application = applications[(app_seq, app_version)]
                target = max(target, next_clock)
                last_activity = max(last_activity, next_clock)
                if phase == 0:
                    release_result = engine.release(app_seq, app_version, next_clock)
                    process_dispatched(release_result)
                else:
                    acquire_result = engine.acquire(application, next_clock)
                    process_dispatched(acquire_result)
                    if acquire_result["status"] == "LEASED":
                        record_issue(acquire_result["lease"])
                        schedule_release(acquire_result["lease"])
                continue
            if not result.get("dispatched"):
                break
            target = max(target, engine.current_clock() + idle_timeout + clock_step)

        status = engine.status()
    finally:
        engine.close()
    return {
        "initialization": init,
        "leases_issued": issued,
        "closed_events": closed,
        "status": status,
    }

#!/usr/bin/env python3
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from fusion_diag.config import load_v1, write_v1  # noqa: E402
from fusion_diag.generate import generate_workspace  # noqa: E402
from fusion_diag.state import StageLock, StateStore  # noqa: E402


def run_cli(*args: str, timeout: int = 60) -> subprocess.CompletedProcess[str]:
    command = [sys.executable, "-m", "fusion_diag", *args]
    return subprocess.run(
        command,
        cwd=ROOT,
        text=True,
        capture_output=True,
        timeout=timeout,
        check=False,
    )


def parse_stdout(process: subprocess.CompletedProcess[str]) -> dict[str, Any]:
    if not process.stdout.strip():
        raise RuntimeError(
            f"command produced no stdout (exit={process.returncode}): {process.stderr}"
        )
    return json.loads(process.stdout)


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def write_markdown(report: dict[str, Any], path: Path) -> None:
    lines = [
        "# Fusion Diagnostics Acceptance",
        "",
        f"- Status: **{report['status']}**",
        f"- Seed: `{report['seed']}`",
        f"- Python: `{report['environment']['python']}`",
        f"- NumPy: `{report['environment']['numpy']}`",
        f"- SQLite: `{report['environment']['sqlite']}`",
        "",
        "## End-to-end checks",
        "",
        "| Check | Result | Evidence |",
        "| --- | --- | --- |",
    ]
    for check in report["checks"]:
        lines.append(
            f"| {check['name']} | {check['status']} | {check['evidence']} |"
        )
    lines.extend(
        [
            "",
            "## Incremental closure",
            "",
            "| Scenario | Recomputed | Reused | Full-diff |",
            "| --- | ---: | ---: | --- |",
        ]
    )
    for name, summary in report["incremental"].items():
        lines.append(
            f"| {name} | {len(summary['recomputed'])} "
            f"({', '.join(summary['recomputed'])}) | "
            f"{len(summary['reused'])} | {summary['diff_coverage']} |"
        )
    lines.extend(
        [
            "",
            "## Byte hashes",
            "",
            f"- Base batch: `{report['hashes']['base_batch']}`",
            f"- TF revision batch: `{report['hashes']['tf_revision_batch']}`",
            f"- Interactive q0006 body: `{report['hashes']['interactive_q0006']}`",
            f"- Interactive/batch q0006 match: "
            f"`{report['interactive']['byte_identical']}`",
            "",
            "## Query latency",
            "",
            f"- q0006 mean: `{report['interactive']['latency']['mean_ms']} ms`",
            f"- q0006 p50: `{report['interactive']['latency']['p50_ms']} ms`",
            f"- q0006 p95: `{report['interactive']['latency']['p95_ms']} ms`",
            f"- Features: `{json.dumps(report['interactive']['latency']['features'], sort_keys=True)}`",
            f"- Estimate: `{report['interactive']['latency']['estimate_model']}`",
            "",
            "## Recovery and errors",
            "",
            f"- Crash checkpoint: `{report['recovery']['resumed_from']}`",
            f"- Committed query count after resume: "
            f"`{report['recovery']['committed_count']}`",
            f"- q0006 commit audit count after rerun: "
            f"`{report['recovery']['audit_count_q0006']}`",
            f"- Stage busy error: `{report['errors']['stage_busy']}`",
            f"- Resource limit error: `{report['errors']['resource_limit']}`",
            f"- Corrupt input error: `{report['errors']['corrupt_input']}`",
            "",
            "Generated by `python3 scripts/run_acceptance.py`.",
            "",
        ]
    )
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    started = time.perf_counter()
    samples = ROOT / "samples"
    runs = ROOT / "runs" / "acceptance"
    artifacts = ROOT / "artifacts"
    for path in (samples, runs):
        shutil.rmtree(path, ignore_errors=True)
    artifacts.mkdir(parents=True, exist_ok=True)
    for name in ("acceptance.json", "acceptance_report.md"):
        target = artifacts / name
        if target.exists():
            target.unlink()
    generate_workspace(samples)
    runs.mkdir(parents=True, exist_ok=True)
    checks: list[dict[str, str]] = []

    def check(name: str, condition: bool, evidence: str) -> None:
        checks.append(
            {
                "name": name,
                "status": "PASS" if condition else "FAIL",
                "evidence": evidence,
            }
        )

    validate = run_cli(
        "validate",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
        "--prepared-out",
        "runs/acceptance/prepared.json",
        "--stats-out",
        "runs/acceptance/stats.json",
    )
    parsed_validate = parse_stdout(validate)
    check(
        "Deterministic ingestion",
        validate.returncode == 0
        and parsed_validate["documents"] == 32
        and parsed_validate["queries"] == 12,
        "32 documents / 12 queries; prepared and stats files written",
    )

    base_work = "runs/acceptance/base"
    base_batch = run_cli(
        "batch",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
        "--workdir",
        base_work,
        "--out",
        f"{base_work}/batch.jsonl",
        "--report",
        f"{base_work}/report.json",
        "--mode",
        "full",
        "--verify-full",
    )
    base_report = load_json(ROOT / base_work / "report.json")
    base_hash = base_report["output_sha256"]
    check(
        "Full batch matches clean full recomputation",
        base_batch.returncode == 0
        and base_report["diff_coverage"]["status"] == "match",
        f"12/12 byte-identical; sha256={base_hash}",
    )

    second = run_cli(
        "batch",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
        "--workdir",
        base_work,
        "--out",
        f"{base_work}/batch_second.jsonl",
        "--report",
        f"{base_work}/report_second.json",
    )
    second_report = load_json(ROOT / base_work / "report_second.json")
    check(
        "Unchanged rerun reuses every committed query",
        second.returncode == 0
        and second_report["recomputed_query_ids"] == []
        and second_report["committed_record_count"] == 0
        and second_report["output_sha256"] == base_hash,
        "recompute=[], commit_audit unchanged, output sha256 unchanged",
    )

    raw_query = run_cli(
        "query",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
        "--workdir",
        base_work,
        "--query-id",
        "q0006",
        "--raw",
        "--compare-batch",
        f"{base_work}/batch.jsonl",
    )
    interactive = run_cli(
        "query",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
        "--workdir",
        base_work,
        "--query-id",
        "q0006",
        "--repeat",
        "20",
        "--compare-batch",
        f"{base_work}/batch.jsonl",
    )
    interactive_data = parse_stdout(interactive)
    check(
        "Interactive query equals batch record",
        raw_query.returncode == 0
        and interactive_data["batch_comparison"]["status"] == "byte_identical",
        "q0006 canonical body sha256 "
        + interactive_data["batch_comparison"]["interactive_sha256"],
    )
    check(
        "Latency observation and feature estimate",
        len(interactive_data["latency"]["samples_ms"]) == 20
        and interactive_data["latency"]["features"]["normalization_calculations"] > 0,
        "mean={mean_ms} ms, p95={p95_ms} ms".format(
            **interactive_data["latency"]
        ),
    )

    tf_report_path = "runs/acceptance/tf/report.json"
    tf_run = run_cli(
        "batch",
        "--docs",
        "samples/variants/docs_tf_revision.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
        "--workdir",
        base_work,
        "--out",
        "runs/acceptance/tf/batch.jsonl",
        "--report",
        tf_report_path,
        "--verify-full",
    )
    tf_report = load_json(ROOT / tf_report_path)
    check(
        "TF-only revision uses targeted invalidation",
        tf_run.returncode == 0
        and tf_report["recomputed_query_ids"] == ["q0001", "q0006"]
        and tf_report["diff_coverage"]["status"] == "match",
        "recomputed q0001,q0006; reused 10 queries; full diff 12/12 match",
    )

    weight_work = "runs/acceptance/weight"
    run_cli(
        "batch",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
        "--workdir",
        weight_work,
        "--out",
        f"{weight_work}/base.jsonl",
        "--mode",
        "full",
    )
    weight_run = run_cli(
        "batch",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/variants/config_prefix_weight_v1.json",
        "--workdir",
        weight_work,
        "--out",
        f"{weight_work}/changed.jsonl",
        "--report",
        f"{weight_work}/report.json",
        "--verify-full",
    )
    weight_report = load_json(ROOT / weight_work / "report.json")
    check(
        "Route-weight change only recomputes route users",
        weight_run.returncode == 0
        and weight_report["reuse_reasons"].get("q0011") == "unused_route_weight_changed"
        and weight_report["diff_coverage"]["status"] == "match",
        "recomputed="
        + ",".join(weight_report["recomputed_query_ids"])
        + "; reused q0011; full diff match",
    )

    norm_work = "runs/acceptance/norm"
    run_cli(
        "batch",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
        "--workdir",
        norm_work,
        "--out",
        f"{norm_work}/base.jsonl",
        "--mode",
        "full",
    )
    norm_run = run_cli(
        "batch",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/variants/config_rank_norm_v1.json",
        "--workdir",
        norm_work,
        "--out",
        f"{norm_work}/changed.jsonl",
        "--report",
        f"{norm_work}/report.json",
        "--verify-full",
    )
    norm_report = load_json(ROOT / norm_work / "report.json")
    check(
        "Normalization change invalidates all queries",
        norm_run.returncode == 0
        and norm_report["reused_query_ids"] == []
        and norm_report["diff_coverage"]["status"] == "match",
        "12 recomputed / 0 reused; full diff match",
    )

    migration_run = run_cli(
        "migrate",
        "--source",
        "samples/config_v1.json",
        "--destination",
        "runs/acceptance/migrated_v2",
        "--source-schema",
        "v1",
        "--destination-schema",
        "v2",
        "--report",
        "runs/acceptance/migrate.json",
    )
    migration_report = load_json(ROOT / "runs/acceptance/migrate.json")
    downgrade_run = run_cli(
        "migrate",
        "--source",
        "runs/acceptance/migrated_v2",
        "--destination",
        "runs/acceptance/migrated_v1.json",
        "--source-schema",
        "v2",
        "--destination-schema",
        "v1",
    )
    downgrade_report = parse_stdout(downgrade_run)
    check(
        "v1/v2 migration and digest preservation",
        migration_run.returncode == 0
        and downgrade_run.returncode == 0
        and downgrade_report["dropped_tombstones"],
        "v2 fields completed with provenance; tombstone drop rule explicit",
    )

    resume_work = "runs/acceptance/resume"
    crash = run_cli(
        "batch",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
        "--workdir",
        resume_work,
        "--out",
        f"{resume_work}/out.jsonl",
        "--crash-after",
        "fusion",
    )
    resumed = run_cli(
        "batch",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
        "--workdir",
        resume_work,
        "--out",
        f"{resume_work}/out.jsonl",
        "--report",
        f"{resume_work}/report.json",
        "--verify-full",
    )
    resume_report = load_json(ROOT / resume_work / "report.json")
    state = StateStore(ROOT / resume_work / "state")
    audit_before_rerun = state.commit_audit_count("q0006")
    rerun = run_cli(
        "batch",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
        "--workdir",
        resume_work,
        "--out",
        f"{resume_work}/out2.jsonl",
    )
    audit_after_rerun = state.commit_audit_count("q0006")
    check(
        "Forced termination resumes from checkpoint",
        crash.returncode == 137
        and resumed.returncode == 0
        and resume_report["resumed_from"]["stage"] == "fusion"
        and resume_report["diff_coverage"]["status"] == "match"
        and audit_before_rerun == 1
        and audit_after_rerun == 1
        and rerun.returncode == 0,
        "crash exit=137; resumed at fusion; q0006 audit count remains 1",
    )

    busy_result: dict[str, Any]
    lock_path = ROOT / "runs/acceptance/busy/stage.lock"
    with StageLock(lock_path):
        busy = run_cli(
            "query",
            "--docs",
            "samples/docs.jsonl",
            "--queries",
            "samples/queries.jsonl",
            "--vocab",
            "samples/vocab.txt",
            "--config",
            "samples/config_v2",
            "--workdir",
            "runs/acceptance/busy",
            "--query-id",
            "q0001",
            "--raw",
        )
    busy_result = json.loads(busy.stderr)
    check(
        "Concurrent stage ownership returns E_STAGE_BUSY",
        busy.returncode == 2 and busy_result["error"] == "E_STAGE_BUSY",
        "second entrant rejected without waiting",
    )

    resource_config = ROOT / "runs/acceptance/resource/config.json"
    source_config = load_v1(samples / "config_v1.json")
    payload = json.loads(json.dumps(source_config.payload))
    payload["fusion"]["memory_limit_mb"] = 1
    write_v1(
        resource_config,
        payload,
        config_id="tiny-memory",
        effective_seconds=0.0,
    )
    resource = run_cli(
        "batch",
        "--docs",
        "samples/docs.jsonl",
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        str(resource_config),
        "--workdir",
        "runs/acceptance/resource",
        "--out",
        "runs/acceptance/resource/out.jsonl",
        "--no-lock",
    )
    resource_result = json.loads(resource.stderr)
    check(
        "Resident-memory ceiling returns E_RESOURCE_LIMIT",
        resource.returncode == 2
        and resource_result["error"] == "E_RESOURCE_LIMIT",
        "projected RSS exceeds 1 MiB before ingestion work",
    )

    invalid_docs = ROOT / "runs/acceptance/invalid_docs.jsonl"
    invalid_docs.write_text(
        '{"doc_id":"bad","terms":[{"term":"alpha","tf":1}],'
        '"doc_len":1,"category":"books","quality_score":2.0}\n',
        encoding="utf-8",
    )
    corrupt = run_cli(
        "validate",
        "--docs",
        str(invalid_docs),
        "--queries",
        "samples/queries.jsonl",
        "--vocab",
        "samples/vocab.txt",
        "--config",
        "samples/config_v2",
    )
    corrupt_result = json.loads(corrupt.stderr)
    check(
        "Corrupt input reports line and field",
        corrupt.returncode == 2
        and corrupt_result["error"] == "E_FORMAT_CORRUPT"
        and corrupt_result["line"] == 1
        and corrupt_result["field"] == "quality_score",
        "E_FORMAT_CORRUPT line=1 field=quality_score",
    )

    all_pass = all(item["status"] == "PASS" for item in checks)
    import numpy
    import sqlite3 as sqlite_module

    report = {
        "schema": "fusion_diag.acceptance.v1",
        "status": "PASS" if all_pass else "FAIL",
        "seed": 20261127,
        "environment": {
            "python": sys.version.split()[0],
            "numpy": numpy.__version__,
            "sqlite": sqlite_module.sqlite_version,
        },
        "duration_ms": round((time.perf_counter() - started) * 1000.0, 3),
        "checks": checks,
        "hashes": {
            "base_batch": base_hash,
            "tf_revision_batch": tf_report["output_sha256"],
            "interactive_q0006": interactive_data["batch_comparison"][
                "interactive_sha256"
            ],
        },
        "incremental": {
            "tf_only": {
                "recomputed": tf_report["recomputed_query_ids"],
                "reused": tf_report["reused_query_ids"],
                "diff_coverage": tf_report["diff_coverage"]["status"],
            },
            "route_weight": {
                "recomputed": weight_report["recomputed_query_ids"],
                "reused": weight_report["reused_query_ids"],
                "diff_coverage": weight_report["diff_coverage"]["status"],
            },
            "normalization": {
                "recomputed": norm_report["recomputed_query_ids"],
                "reused": norm_report["reused_query_ids"],
                "diff_coverage": norm_report["diff_coverage"]["status"],
            },
        },
        "interactive": {
            "byte_identical": interactive_data["batch_comparison"]["status"]
            == "byte_identical",
            "latency": interactive_data["latency"],
            "top_k": interactive_data["result"]["top_k"],
        },
        "recovery": {
            "resumed_from": resume_report["resumed_from"],
            "committed_count": len(state.get_all_committed()),
            "audit_count_q0006": audit_after_rerun,
        },
        "errors": {
            "stage_busy": busy_result["error"],
            "resource_limit": resource_result["error"],
            "corrupt_input": corrupt_result,
        },
        "migration": {
            "v1_to_v2": migration_report,
            "v2_to_v1": downgrade_report,
        },
    }
    acceptance_path = artifacts / "acceptance.json"
    acceptance_path.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    write_markdown(report, artifacts / "acceptance_report.md")
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0 if all_pass else 1


if __name__ == "__main__":
    raise SystemExit(main())
